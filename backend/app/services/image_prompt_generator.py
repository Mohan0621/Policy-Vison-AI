"""
image_prompt_generator.py
--------------------------
Advanced Image Prompt Engineering Component for PolicyVision AI.

Synthesizes rich, diffusion-ready image generation prompts based on the
structured VisualPlan generated by the VisualPlanningEngine.

Key Responsibilities:
1. Translates policy domain & visual planning directives into natural language
   cinematography briefs for FLUX.1 / SDXL Turbo.
2. Specifies main subject, lighting, composition, camera perspective, materials,
   depth, and color palette.
3. Enforces negative constraints to prevent blurry text, messy floating artifacts,
   and visual noise.
4. Leaves typography and numeric data to the Multilingual Typography Renderer,
   ensuring the diffusion model focuses 100% on generating breathtaking 3D art.
"""

from typing import Tuple
from app.models import ImagePrompt, VisualPlan, VisualStyle


class DynamicImagePromptGenerator:
    """
    Transforms a dynamic VisualPlan into optimized diffusion prompts for FLUX.1 and SDXL.
    """

    def generate_image_prompt(self, plan: VisualPlan) -> ImagePrompt:
        """
        Builds an ImagePrompt populated with the diffusion prompt and attached VisualPlan.
        """
        positive_prompt, negative_prompt = self._compile_diffusion_prompts(plan)

        # Map visual_type to VisualStyle enum for backwards compatibility
        style_enum = (
            VisualStyle.FLOWCHART_DIAGRAM
            if plan.visual_type == "claims"
            else VisualStyle.PROFESSIONAL_INFOGRAPHIC
        )

        return ImagePrompt(
            prompt_text=positive_prompt,
            negative_prompt=negative_prompt,
            style=style_enum,
            language=plan.language,
            text_overlays=[],
            source_citations=plan.source_citations,
            structured_data={
                "title": plan.title,
                "subtitle": plan.subtitle,
                "hero_metric": plan.hero_metric,
                "sections": [
                    {
                        "heading": s.heading,
                        "amount_or_metric": s.amount_or_metric,
                        "description": s.description,
                        "badge": s.badge,
                        "subbadge": s.subbadge,
                    }
                    for s in plan.sections
                ],
            },
            visual_plan=plan,
        )

    def _compile_diffusion_prompts(self, plan: VisualPlan) -> Tuple[str, str]:
        """
        Synthesizes high-end photographic / 3D prompt for diffusion backends.
        """
        base_subject = plan.hero_artwork_prompt or "3D isometric insurance protection shield"
        palette = plan.color_palette or {}
        primary_color = palette.get("primary", "#1E3A8A")
        accent_color = palette.get("accent", "#10B981")

        positive = (
            f"Commercial 3D editorial artwork of {base_subject}. "
            f"Art Direction: {plan.art_direction}. "
            f"Composition: Centered isometric perspective, clean square framing, ample negative space. "
            f"Materials: Translucent frosted glassmorphism, beveled metallic accents in {primary_color}, "
            f"vibrant luminescent core in {accent_color}, satin finish. "
            f"Lighting: Volumetric diffused studio softbox lighting, gentle rim light, subtle ambient occlusion. "
            f"Rendering: Octane Render style, ray-traced reflections, hyper-detailed, photorealistic, 8k resolution, "
            f"clean white background, award-winning visual craft, zero text."
        )

        negative = (
            "blurry, noisy, low resolution, pixelated, distorted geometry, amateur render, "
            "cluttered background, dark muddy shadows, flat cartoon, misspelled floating text, "
            "watermarks, signatures, ugly artifacts, human deformities"
        )

        return positive, negative
